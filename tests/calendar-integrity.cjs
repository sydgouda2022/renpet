const {chromium}=require('playwright');
const assert=require('node:assert/strict');
async function main(){
 const browser=await chromium.launch({channel:'chrome',headless:true,args:['--no-sandbox']});
 try{
  const context=await browser.newContext({viewport:{width:1024,height:768},serviceWorkers:'block',timezoneId:'Africa/Cairo'});
  const page=await context.newPage();page.setDefaultTimeout(10000);
  page.on('dialog',d=>d.accept());
  await page.goto('http://127.0.0.1:8765/',{waitUntil:'domcontentloaded'});
  await page.locator('.month-agenda').waitFor();
  await page.locator('header [data-new]').click();
  const form=page.locator('#event-editor');
  await form.locator('[name=title]').fill('Three-day preservation test');
  await form.locator('[name=egyYear]').selectOption('6282');
  await form.locator('[name=egyMonth]').selectOption('2');
  await form.locator('[name=egyDay]').selectOption('26');
  assert.equal(await form.locator('[name=endEgyDay]').inputValue(),'26','End date should follow start automatically');
  await form.locator('[name=endEgyDay]').selectOption('28');
  await form.locator('.save-button').click();
  await page.locator('.save-confirmation').waitFor();
  const item=await page.evaluate(()=>JSON.parse(localStorage.getItem('renpet.scheduler.v1')).items.find(i=>i.title==='Three-day preservation test'));
  assert.ok(item);assert.equal(item.endDay-item.startDay,2);
  await page.locator('[data-next]').click();
  const mid=await page.locator('.timeline-event:has-text("Three-day preservation test")').evaluate(el=>el.style.top);
  assert.equal(mid,'0px','Middle day should start at midnight');
  await page.locator('.timeline-event:has-text("Three-day preservation test")').click();
  assert.equal(await page.locator('#event-editor [name=egyDay]').inputValue(),'26','Editing from middle must keep first day');
  assert.equal(await page.locator('#event-editor [name=endEgyDay]').inputValue(),'28','Editing from middle must preserve end date');
  await page.locator('#event-editor .save-button').click();
  const after=await page.evaluate(()=>JSON.parse(localStorage.getItem('renpet.scheduler.v1')).items.find(i=>i.title==='Three-day preservation test'));
  assert.equal(after.startDay,item.startDay);
  assert.equal(after.endDay,item.endDay);
  await page.locator('[data-back]').click();
  const chosen=page.locator('.month-section .date[data-date="'+(item.startDay+1)+'"]');
  await chosen.click();
  await page.locator('.day-page').waitFor();
  assert.equal(await page.locator('.timeline-event:has-text("Three-day preservation test")').count(),1,'iPad day selection opens its appointments');
  await page.locator('[data-back]').click();
  assert.equal(await chosen.getAttribute('aria-pressed'),'true','Returning to month retains the selected day');
  assert.equal(await page.locator('.month-agenda .event-row:has-text("Three-day preservation test")').count(),1);
  // Saving one weekly occurrence must not truncate the original series.
  await page.locator('header [data-new]').click();
  const weekly=page.locator('#event-editor');
  await weekly.locator('[name=title]').fill('Weekly original');
  await weekly.locator('[name=egyYear]').selectOption('6282');
  await weekly.locator('[name=egyMonth]').selectOption('2');
  await weekly.locator('[name=egyDay]').selectOption('26');
  await weekly.locator('.advanced-fields summary').click();
  await weekly.locator('[name=repeat]').selectOption('weekly');
  await weekly.locator('.save-button').click();
  await page.locator('.save-confirmation').waitFor();
  for(let i=0;i<7;i++)await page.locator('[data-next]').click();
  await page.locator('.timeline-event:has-text("Weekly original")').click();
  const occurrence=page.locator('#event-editor');
  assert.equal(await occurrence.locator('[name=repeatScope]').inputValue(),'series');
  await occurrence.locator('[name=repeatScope]').selectOption('one');
  await occurrence.locator('[name=title]').fill('One altered week');
  await occurrence.locator('.save-button').click();
  await page.locator('.save-confirmation').waitFor();
  const records=await page.evaluate(()=>JSON.parse(localStorage.getItem('renpet.scheduler.v1')).items);
  const series=records.find(i=>i.title==='Weekly original');
  const detached=records.find(i=>i.title==='One altered week');
  assert.equal(series.repeat,'weekly');
  assert.ok(series.excludedDays.includes(series.startDay+7));
  assert.equal(detached.startDay,series.startDay+7);
  assert.equal(detached.repeat,'none');
  await context.close();
  console.log('Renpet multi-day, occurrence editing + iPad agenda regression OK');
 }finally{await browser.close();}
}
main().catch(e=>{console.error(e);process.exitCode=1});
