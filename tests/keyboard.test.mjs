import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {COPTIC_LETTERS,COP_NUMBERS,EGY_NUMBERS,wordRange,suggestions,deleteGrapheme} from '../web/keyboard-core.js';
import {egyptianSignPages} from '../web/keyboard-api.mjs';
import {createKeyboardFromData,API_VERSION} from '../web/keyboards/egy/keyboard_api.mjs';
import {prepareKeyboardIndex,predictKeyboard,PREDICTION_API_VERSION} from '../web/keyboards/cop/keyboard_search.mjs';
const read=async p=>JSON.parse(await readFile(new URL('../web/'+p,import.meta.url),'utf8'));
const coptic=await read('coptic-lexicon/lexicon.json'),egyptian=await read('lexicon/lexicon.json');
assert.equal(COPTIC_LETTERS.length,32);
assert.equal(new Set(COPTIC_LETTERS).size,32);
assert.equal(COP_NUMBERS.length,12);
assert.equal(EGY_NUMBERS.length,15);
assert.equal(PREDICTION_API_VERSION,2);
assert.match(API_VERSION,/^2\.\d+\.\d+$/,'Renpet requires compatible Egyptian keyboard API v2');
const pages=egyptianSignPages();
for(const group of ['uni','bi','tri'])assert.ok(pages[group].length>15);
const engine=createKeyboardFromData({lexicon:egyptian});
assert.ok(engine.getSigns('uni').some(sign=>sign.code==='M17A'));
assert.ok(engine.validate('𓄿𓈖'));
assert.equal(engine.searchSigns('M17A')[0].code,'M17A');
assert.equal(engine.predict('𓄿')[0].text,'𓄿');
assert.equal(suggestions('𓄿','egy',egyptian)[0].text,'𓄿');
assert.ok(suggestions('𓄿','egy',egyptian).length>1);
assert.equal(suggestions('𓄿','egy',null)[0].text,'𓄿');
assert.equal(egyptian.entries.length,egyptian.metadata.spelling_records);
const ci=prepareKeyboardIndex('cop',coptic);
assert.equal(predictKeyboard(ci,'ⲛ')[0].text,'ⲛ');
assert.equal(suggestions('ⲛ','cop',coptic)[0].text,'ⲛ');
assert.ok(suggestions('ⲛ','cop',coptic).length>=2);
for(const [dialect,mask] of [['sahidic',1],['bohairic',2]]){
 const candidates=suggestions('ⲡ','cop',coptic,{},20,{dialect});
 assert.ok(candidates.slice(1).every(x=>x.dialects&mask));
}
assert.equal(wordRange('ⲁⲡⲉ ⲥⲙ',7,'cop').raw,'ⲥⲙ');
assert.deepEqual(wordRange('ⲥⲙⲉ',2,'cop'),{start:0,end:3,raw:'ⲥⲙⲉ'});
assert.equal(wordRange('𓄿𓅓 𓈖𓏏',9,'egy').raw,'𓈖𓏏');
assert.equal(deleteGrapheme('𓄿𓂝',4,4).start,2);
assert.equal(deleteGrapheme('ⲁ̅',2,2).start,0);
assert.equal(coptic.rows.length,coptic.metadata.spelling_records);
console.log('Independent Coptic and Egyptian APIs verified within Renpet');
