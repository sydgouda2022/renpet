"""Build one versioned, offline-safe service worker for Renpet.

Precache uses canonical URLs. Runtime requests may carry ?v= for PWA
cache-busting; Cache.match(ignoreSearch=True) resolves those while offline.
Keep at most one previous complete cache during atomic SW upgrades.
"""
from __future__ import annotations

import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
version = json.loads((ROOT / "web/data.json").read_text(encoding="utf-8"))["version"]
if not isinstance(version, str) or not version.count(".") == 2:
    raise SystemExit("Invalid Renpet release version")
web = ROOT / "web"
files = [
    "./" + p.relative_to(web).as_posix()
    for p in sorted(web.rglob("*"))
    # JSON + manifests are the installed prediction engines. SQLite is a
    # release/build artifact and never opened by the browser: do not precache
    # duplicate multi-megabyte database files on every PWA update.
    if p.is_file() and p.name not in {"sw.js", "_headers"} and p.suffix != ".sqlite3"
]
required = {"./index.html", "./app.js", "./data.json", "./ui.css",
            "./calendar.js", "./scheduler.js", "./locales.js",
            "./time-editor.js", "./clock.js", "./keyboard.js",
            "./calendar-presentation.mjs", "./season-theme.css",
            "./assets/seasons/akhet.webp", "./assets/seasons/peret.webp",
            "./assets/seasons/shemu.webp"}
if not required.issubset(files):
    raise SystemExit("Missing offline boot files: " + repr(required - set(files)))
stamp = hashlib.sha256(b"".join(
    p.encode() + hashlib.sha256((web / p.removeprefix("./")).read_bytes()).digest()
    for p in files
)).hexdigest()[:12]
template = r"""// Generated by tools/build_service_worker.py; do not edit by hand.
const CACHE = '__CACHE__';
const ASSETS = __ASSETS__;
const OLD_PREFIX = 'renpet-';
self.addEventListener('install', event => {
 event.waitUntil((async () => {
  // Install is atomic: a broken connection cannot replace the installed app.
  const cache = await caches.open(CACHE);
  await cache.addAll(ASSETS);
  await self.skipWaiting();
 })());
});
self.addEventListener('activate', event => {
 event.waitUntil((async () => {
  const existing = (await caches.keys()).filter(k => k.startsWith(OLD_PREFIX));
  // Retain one previous complete release while already-open clients finish.
  const older = existing.filter(k => k !== CACHE);
  const keep = new Set([CACHE, ...older.slice(-1)]);
  await Promise.all(existing.filter(k => !keep.has(k)).map(k => caches.delete(k)));
  await self.clients.claim();
 })());
});
self.addEventListener('fetch', event => {
 if (event.request.method !== 'GET') return;
 const url = new URL(event.request.url);
 if (url.origin !== self.location.origin) return;
 if (event.request.mode === 'navigate') {
  event.respondWith((async () => {
   try {
    const response = await fetch(event.request);
    if (response.ok) return response;
    throw new Error('Navigation response: ' + response.status);
   } catch {
    // The offline index and its module graph are from the same installation.
    const cache = await caches.open(CACHE);
    return await cache.match('./index.html') ||
      await caches.match('./index.html', {ignoreSearch: true}) ||
      Response.error();
   }
  })());
  return;
 }
 event.respondWith((async () => {
  const cache = await caches.open(CACHE);
  // Critical: HTML requests app.js?v=6.x but precache stored ./app.js.
  // Strip version queries to their canonical cache key first. Explicit keys
  // work on WebKit versions that implement ignoreSearch inconsistently.
  const canonical = new URL(event.request.url);
  canonical.search = '';
  canonical.hash = '';
  const cached = await cache.match(canonical.href) ||
    await cache.match(event.request, {ignoreSearch: true});
  // The source registry can be removed or amended between PWA releases.
  // Cache-first previously kept six obsolete festival choices visible even
  // after production contained only four. Prefer the network when online,
  // but keep the installed snapshot for genuinely offline use.
  if (url.pathname.endsWith('/festival-sources.json') ||
      url.pathname.includes('/festival-packs/')) {
    try {
      const fresh = await fetch(event.request, {cache: 'no-store'});
      if (fresh.ok) {
        event.waitUntil(cache.put(canonical.href, fresh.clone()).catch(() => {}));
        return fresh;
      }
    } catch {}
    return cached ||
      new Response('Festival catalog unavailable offline', {status: 503});
  }
  if (cached) return cached;
  try {
   const response = await fetch(event.request);
   if (response.ok) event.waitUntil(cache.put(event.request, response.clone()).catch(() => {}));
   return response;
  } catch {
   return await caches.match(event.request, {ignoreSearch: true}) ||
     new Response('Renpet offline asset unavailable', {status: 503, headers: {'Content-Type': 'text/plain'}});
  }
 })());
});
"""
text = template.replace("__CACHE__", f"renpet-{version}-{stamp}") \
               .replace("__ASSETS__", json.dumps(files, ensure_ascii=False, separators=(",", ":")))
(web / "sw.js").write_text(text, encoding="utf-8")
print(f"Built Renpet {version} service worker with {len(files)} cacheable assets and query-safe offline paths")

