"""Build one versioned, offline-safe service worker for Renpet.

Precache uses canonical URLs. Runtime requests may carry ?v= for PWA
cache-busting; Cache.match(ignoreSearch=True) resolves those while offline.
Only the current release cache is retained.
"""
from __future__ import annotations

import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
version = json.loads((ROOT / "web/data.json").read_text(encoding="utf-8"))["version"]
if not isinstance(version, str) or not version.count(".") == 2:
    raise SystemExit("Invalid Renpet release version")
web = ROOT / "web"
files = [
    "./" + p.relative_to(web).as_posix()
    for p in sorted(web.rglob("*"))
    # JSON + manifests are the installed prediction engines. SQLite is a
    # release/build artifact and never opened by the browser: do not precache
    # duplicate multi-megabyte database files on every PWA update.
    if p.is_file() and p.name not in {"sw.js", "_headers"} and p.suffix != ".sqlite3"
]
required = {"./index.html", "./app.js", "./data.json", "./ui.css",
            "./calendar.js", "./scheduler.js", "./locales.js",
            "./time-editor.js", "./clock.js", "./keyboard.js",
            "./calendar-presentation.mjs", "./season-theme.css",
            "./assets/seasons/akhet.webp", "./assets/seasons/peret.webp",
            "./assets/seasons/shemu.webp"}
if not required.issubset(files):
    raise SystemExit("Missing offline boot files: " + repr(required - set(files)))
stamp = hashlib.sha256(b"".join(
    p.encode() + hashlib.sha256((web / p.removeprefix("./")).read_bytes()).digest()
    for p in files
)).hexdigest()[:12]
# Lexicons install independently. Lazy-cache nonessential numeral SVG images.
# The initial offline release needs only day numerals and today's Egyptian year.
from datetime import date
days_since_epoch = (date.today() - date(2026, 9, 11)).days
def egyptian_start_offset(year):
    return 365 * (year - 6268) + (year - 1) // 4 - (6268 - 1) // 4
current_egy_year = 6268 + days_since_epoch // 365
while egyptian_start_offset(current_egy_year) > days_since_epoch:
    current_egy_year -= 1
while egyptian_start_offset(current_egy_year + 1) <= days_since_epoch:
    current_egy_year += 1
core_numerals = {str(n) for n in range(1,32)} | {str(current_egy_year+i) for i in (-1,0,1)}
precache = [p for p in files if p not in {'./lexicon/lexicon.json', './coptic-lexicon/lexicon.json'}
 and (not p.startswith('./assets/numerals/') or Path(p).stem in core_numerals)]
template = r"""// Generated by tools/build_service_worker.py; do not edit by hand.
const CACHE = '__CACHE__';
const ASSETS = __ASSETS__;
const OLD_PREFIX = 'renpet-';
const SHELL = './index.html';

// Safari does not permit a service worker to serve a navigation response
// that carries a followed redirect. Some Cloudflare static hosts redirect
// /index.html to /, and CacheStorage preserves Response.redirected.
// Rebuild a same-origin HTML response with a fresh (non-redirected) identity.
// This copies headers/body but not the response URL or redirect history.
function navigationHtml(response) {
 if (!response || !response.ok) throw new Error('Renpet shell unavailable');
 if (response.url && new URL(response.url).origin !== self.location.origin)
  throw new Error('Renpet shell redirected to another origin');
 const headers = new Headers(response.headers);
 headers.set('Content-Type', 'text/html; charset=utf-8');
 headers.delete('Location');
 // A fetch body is decoded before JavaScript receives it. Keeping the
 // original wire-size/encoding headers would misdescribe this new response.
 headers.delete('Content-Encoding');
 headers.delete('Content-Length');
 // A new Response never carries Response.redirected, even when its source
 // was fetched by following a 301/302 from /index.html to /.
 return new Response(response.body, {
  status: response.status, statusText: response.statusText, headers
 });
}
self.addEventListener('install', event => {
 event.waitUntil((async () => {
  // Install remains atomic. The canonical shell is stored independently:
  // cache.addAll would otherwise save Safari-invalid redirected HTML.
  const cache = await caches.open(CACHE);
  await cache.addAll(ASSETS.filter(asset => asset !== SHELL));
  const shell = await fetch(new URL(SHELL, self.registration.scope), {cache: 'no-store'});
  await cache.put(SHELL, navigationHtml(shell));
  await self.skipWaiting();
 })());
});
self.addEventListener('activate', event => {
 event.waitUntil((async () => {
  const existing = (await caches.keys()).filter(k => k.startsWith(OLD_PREFIX));
  await Promise.all(existing.filter(key => key !== CACHE).map(key => caches.delete(key)));
  await self.clients.claim();
 })());
});
self.addEventListener('fetch', event => {
 if (event.request.method !== 'GET') return;
 const url = new URL(event.request.url);
 if (url.origin !== self.location.origin) return;
 if (event.request.mode === 'navigate') {
  event.respondWith((async () => {
   try {
    const response = await fetch(event.request);
    if (!response.ok) throw new Error('Navigation response: ' + response.status);
    return navigationHtml(response);
   } catch {
    // Normalise again for existing installations with an older redirected
    // cached shell. This ensures offline Safari navigation is never handed
    // Response.redirected=true, even during an upgrade.
    const cache = await caches.open(CACHE);
    const shell = await cache.match(SHELL) ||
      await caches.match(SHELL, {ignoreSearch: true});
    return shell ? navigationHtml(shell) : Response.error();
   }
  })());
  return;
 }
 event.respondWith((async () => {
  const cache = await caches.open(CACHE);
  // HTML uses versioned URLs, while precache stores canonical unversioned files.
  // Strip version queries to their canonical cache key first. Explicit keys
  // work on WebKit versions that implement ignoreSearch inconsistently.
  const canonical = new URL(event.request.url);
  canonical.search = '';
  canonical.hash = '';
  const cached = await cache.match(canonical.href) ||
    await cache.match(event.request, {ignoreSearch: true});
  // Executable resources must belong to this cached release, never a prior one.
  const executable=/\\.(?:js|mjs|css)$/.test(url.pathname);
  if (executable) {
   try { const fresh=await fetch(event.request,{cache:'no-store'});if(fresh.ok)return fresh; }
   catch{}
  }
  if (cached) return cached;
  try {
   const response = await fetch(event.request);
   if (response.ok) event.waitUntil(cache.put(event.request, response.clone()).catch(() => {}));
   return response;
  } catch {
   return new Response('Renpet offline asset unavailable', {status: 503, headers: {'Content-Type': 'text/plain'}});
  }
 })());
});
"""
text = template.replace("__CACHE__", f"renpet-{version}-{stamp}") \
               .replace("__ASSETS__", json.dumps(precache, ensure_ascii=False, separators=(",", ":")))
(web / "sw.js").write_text(text, encoding="utf-8")
print(f"Built Renpet {version} service worker with {len(precache)} boot assets ({len(files)} total); numeral assets lazy-cache")

